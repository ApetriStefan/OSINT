"""Intelligence artifacts and agent output Pydantic data models."""

from datetime import datetime
import hashlib
from typing import Optional, List
from pydantic import BaseModel, Field, model_validator


class ExtractedEvent(BaseModel):
    """Structured event extracted by Agent 1 (Entity Extractor)."""

    id: Optional[int] = Field(default=None, description="Database record ID")
    article_id: Optional[int] = Field(default=None, description="Referenced raw article ID")
    actor: str = Field(..., description="Political or institutional actor")
    canonical_actor: Optional[str] = Field(default=None, description="Canonical resolved actor name")
    action: str = Field(..., description="Action, claim, or policy maneuver in English")
    verbatim_evidence: str = Field(..., description="Exact verbatim Romanian quote substring from source")
    topic: str = Field(..., description="Strategic domain / topic in English")
    source: Optional[str] = Field(default=None, description="News outlet or source name")
    event_hash: Optional[str] = Field(default=None, description="Deterministic hash for deduplication")
    extracted_at: Optional[datetime] = Field(default=None, description="Timestamp of extraction")

    @model_validator(mode="after")
    def compute_hash(self) -> "ExtractedEvent":
        """Compute unique deterministic hash if not already provided."""
        if not self.event_hash:
            actor_key = (self.canonical_actor or self.actor).strip().lower()
            action_key = self.action.strip().lower()
            quote_key = self.verbatim_evidence.strip().lower()
            combined = f"{actor_key}|{action_key}|{quote_key}"
            self.event_hash = hashlib.sha256(combined.encode("utf-8")).hexdigest()
        return self


class ExtractedEventsContainer(BaseModel):
    """Structured container for Agent 1 LLM response."""

    extracted_events: List[ExtractedEvent] = Field(
        default_factory=list,
        description="List of extracted political/strategic events"
    )


class HistoricalAnomaly(BaseModel):
    """Anomaly or contradiction identified by Agent 2 (Archivist)."""

    id: Optional[int] = Field(default=None, description="Database record ID")
    anomaly_type: str = Field(..., description="Category: contradiction, policy reversal, strategic silence")
    target: str = Field(..., description="Target actor or institution under review")
    past_statement: str = Field(..., description="Verbatim past statement or recorded position")
    current_statement: str = Field(..., description="Today's statement or observed action")
    contradiction_score: float = Field(..., ge=0.0, le=1.0, description="Contradiction magnitude between 0.0 and 1.0")
    analyst_note: str = Field(..., description="Analytical explanation of contradiction significance")
    detected_at: Optional[datetime] = Field(default=None, description="Timestamp of anomaly detection")


class HistoricalAnomaliesContainer(BaseModel):
    """Structured container for Agent 2 LLM response."""

    anomalies: List[HistoricalAnomaly] = Field(
        default_factory=list,
        description="List of detected anomalies or contradictions"
    )


class ThreatVector(BaseModel):
    """Strategic vulnerability or narrative threat identified by Agent 3 (Red Teamer)."""

    id: Optional[int] = Field(default=None, description="Database record ID")
    threat_type: str = Field(..., description="Threat category: vulnerability, weaponized narrative, parasitic framing")
    vulnerable_actor: str = Field(..., description="Target actor exposed to risk")
    exploiting_actor: str = Field(..., description="Actor or party poised to leverage the vulnerability")
    description: str = Field(..., description="Detailed tactical explanation of threat vector")
    detected_at: Optional[datetime] = Field(default=None, description="Timestamp of threat identification")


class ThreatVectorsContainer(BaseModel):
    """Structured container for Agent 3 LLM response."""

    threat_vectors: List[ThreatVector] = Field(
        default_factory=list,
        description="List of tactical threat vectors"
    )


class Prediction(BaseModel):
    """Specific predictive intelligence outcome generated by Agent 4."""

    title: str = Field(..., description="Headline of what to monitor tomorrow")
    confidence_score: int = Field(..., ge=0, le=100, description="Confidence percentage (0-100)")
    justification: str = Field(..., description="Evidence-based reasoning linking raw data to forecast")


class ExecutiveBriefing(BaseModel):
    """Final synthesized intelligence briefing product."""

    date: str = Field(..., description="Date of the briefing")
    raw_markdown: str = Field(..., description="Full synthesized Markdown document")
    corrected_markdown: Optional[str] = Field(default=None, description="Copyedited and grammar-corrected Markdown")
    volatility_level: Optional[str] = Field(default=None, description="Assessed volatility: Scăzut, Mediu, or Ridicat")
